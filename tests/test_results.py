"""Provided: checks on your results file and on the order of your commits.

These fail until you have run the experiment and committed the results.
Do not edit this file.
"""

import csv
import subprocess
from pathlib import Path

ROOT = Path(__file__).parent.parent
RESULTS = ROOT / "results" / "results.csv"
REQUIRED = [
    ("full", "0", "start"),
    ("full", "100", "start"),
    ("full", "2000", "start"),
    ("full", "2000", "middle"),
    ("window", "100", "start"),
    ("summary", "100", "start"),
    ("summary", "2000", "start"),
]


def rows() -> list[dict[str, str]]:
    """Every row of the results file, or none if it does not exist."""
    if not RESULTS.exists():
        return []
    with RESULTS.open(newline="") as handle:
        return list(csv.DictReader(handle))


def count(setting: tuple[str, str, str]) -> int:
    """How many trials the results file holds for one setting."""
    return sum(
        (row["memory"], row["filler"], row["position"]) == setting
        for row in rows()
    )


def git(*arguments: str) -> str:
    """Run a git command in the repository and return its output."""
    return subprocess.run(
        ["git", *arguments], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip()


def test_every_row_came_from_the_model() -> None:
    """Rows exist, and each names the model and has a right or wrong."""
    assert rows()
    for row in rows():
        assert row["model"] == "glm-5.3-flash"
        assert row["correct"] in ("True", "False")


def test_the_in_class_runs_have_three_trials_each() -> None:
    """Full memory at 0, 100 and 2000 filler turns."""
    for setting in REQUIRED[:3]:
        assert count(setting) >= 3, setting


def test_the_other_required_runs_have_three_trials_each() -> None:
    """The middle position, the window, and both summaries."""
    for setting in REQUIRED[3:]:
        assert count(setting) >= 3, setting


def test_one_setting_of_your_own_has_three_trials() -> None:
    """A setting outside the required list, run at least three times."""
    settings = {(r["memory"], r["filler"], r["position"]) for r in rows()}
    own = settings - set(REQUIRED)
    assert any(count(setting) >= 3 for setting in own)


def test_the_prediction_was_committed_before_the_results() -> None:
    """The commit that first adds the results already had a prediction."""
    added = git(
        "log", "--diff-filter=A", "--format=%H", "--", "results/results.csv"
    ).splitlines()
    assert added, "results/results.csv has not been committed"
    before = git("show", f"{added[-1]}^:docs/prediction.md")
    assert before and "TODO" not in before


def test_the_provided_code_is_unchanged() -> None:
    """src/ is as it was in the first commit."""
    first = git("rev-list", "--max-parents=0", "HEAD").splitlines()[-1]
    changed = git("diff", "--name-only", first, "--", "src")
    assert changed == ""
